// Typing effect for hero title (optional enhancement)
const heroTitle = document.querySelector('.hero-text-box h2');
if (heroTitle) {
    const originalText = heroTitle.textContent;
    heroTitle.textContent = '';
    
    let charIndex = 0;
    const typeWriter = () => {
        if (charIndex < originalText.length) {
            heroTitle.textContent += originalText.charAt(charIndex);
            charIndex++;
            setTimeout(typeWriter, 50);
        }
    };
    
    // Start typing effect after a short delay
    setTimeout(typeWriter, 500);
}

// Add subtle mouse tracking effect to hero section
const heroSection = document.querySelector('.hero');
if (heroSection) {
    heroSection.addEventListener('mousemove', (e) => {
        const { clientX, clientY } = e;
        const { innerWidth, innerHeight } = window;
        
        const xPos = (clientX / innerWidth - 0.5) * 20;
        const yPos = (clientY / innerHeight - 0.5) * 20;
        
        const heroTextBox = document.querySelector('.hero-text-box');
        if (heroTextBox) {
            heroTextBox.style.transform = `translate(${xPos}px, ${yPos}px)`;
        }
    });
    
    heroSection.addEventListener('mouseleave', () => {
        const heroTextBox = document.querySelector('.hero-text-box');
        if (heroTextBox) {
            heroTextBox.style.transform = 'translate(0, 0)';
        }
    });
}

// Counter animation for statistics (if you add any stats section)
const animateCounter = (element, target, duration = 2000) => {
    let start = 0;
    const increment = target / (duration / 16);
    
    const updateCounter = () => {
        start += increment;
        if (start < target) {
            element.textContent = Math.floor(start);
            requestAnimationFrame(updateCounter);
        } else {
            element.textContent = target;
        }
    };
    
    updateCounter();
};

